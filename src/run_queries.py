"""Run every query in sql/ against the Chinook database.

For each query this saves the result to results/<name>.csv, and it writes all results
into one readable results/RESULTS.md. It then draws the charts in figures/.

Run:  python src/run_queries.py
"""
from __future__ import annotations

import csv
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "chinook.sqlite"
SQL_DIR = ROOT / "sql"
RESULTS = ROOT / "results"
FIGURES = ROOT / "figures"

plt.rcParams.update({"figure.dpi": 130, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.alpha": 0.25, "font.size": 10})
COLOR = "#1f5c4b"


def run(conn: sqlite3.Connection, path: Path) -> tuple[str, list[str], list[tuple]]:
    sql = path.read_text(encoding="utf-8")
    question = next(
        (line.lstrip("- ").strip() for line in sql.splitlines() if line.startswith("-- Q")), path.stem
    )
    cur = conn.execute(sql)
    cols = [d[0] for d in cur.description]
    return question, cols, cur.fetchall()


def to_markdown(cols: list[str], rows: list[tuple]) -> str:
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.2f}" if abs(v) >= 1000 else f"{v:g}"
        return "" if v is None else str(v)

    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def chart_monthly(cols, rows):
    i_m, i_r, i_a = cols.index("month"), cols.index("revenue"), cols.index("rolling_3m_avg")
    months = [r[i_m] for r in rows]
    fig, ax = plt.subplots(figsize=(10, 3.6))
    ax.bar(range(len(rows)), [r[i_r] for r in rows], color="#c9d8d2", label="Monthly revenue")
    ax.plot(range(len(rows)), [r[i_a] for r in rows], color=COLOR, lw=2, label="3-month rolling average")
    step = max(1, len(months) // 10)
    ax.set_xticks(range(0, len(months), step), months[::step], rotation=0)
    ax.set_ylabel("Revenue (USD)")
    ax.set_title("Monthly revenue, 2021-2025: flat, with no growth trend")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(FIGURES / "monthly_revenue.png")
    plt.close(fig)


def chart_genres(cols, rows):
    i_g, i_s, i_u = cols.index("genre"), cols.index("revenue_share_pct"), cols.index("units_per_catalogue_track")
    top = rows[:10][::-1]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    axes[0].barh([r[i_g] for r in top], [r[i_s] for r in top], color=COLOR)
    axes[0].set_xlabel("Share of revenue (%)")
    axes[0].set_title("Revenue share")
    axes[1].barh([r[i_g] for r in top], [r[i_u] for r in top], color="#b5541c")
    axes[1].set_xlabel("Units sold per track in catalogue")
    axes[1].set_title("Sales efficiency of the catalogue")
    fig.suptitle("Rock earns the most because it has the biggest catalogue; sales per stocked track are similar across genres")
    fig.tight_layout()
    fig.savefig(FIGURES / "genre_performance.png")
    plt.close(fig)


def chart_countries(cols, rows):
    i_c, i_r = cols.index("country"), cols.index("revenue")
    top = rows[:12][::-1]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.barh([r[i_c] for r in top], [r[i_r] for r in top], color=COLOR)
    ax.set_xlabel("Revenue (USD)")
    ax.set_title("Revenue by country (top 12)")
    fig.tight_layout()
    fig.savefig(FIGURES / "revenue_by_country.png")
    plt.close(fig)


CHARTS = {
    "02_monthly_revenue_rolling": chart_monthly,
    "03_revenue_by_country": chart_countries,
    "04_genre_performance": chart_genres,
}


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    FIGURES.mkdir(exist_ok=True)
    conn = sqlite3.connect(DB)
    md = ["# Query results", "", "Generated by `python src/run_queries.py` against `data/chinook.sqlite`.", ""]
    for path in sorted(SQL_DIR.glob("[0-9]*.sql")):
        question, cols, rows = run(conn, path)
        with (RESULTS / f"{path.stem}.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(cols)
            w.writerows(rows)
        shown = rows if len(rows) <= 25 else rows[:25]
        md += [f"## {question}", "", f"Query: [`sql/{path.name}`](../sql/{path.name})", "",
               to_markdown(cols, shown)]
        if len(rows) > len(shown):
            md.append(f"\n_First {len(shown)} of {len(rows)} rows; the full output is in `results/{path.stem}.csv`._")
        md.append("")
        if path.stem in CHARTS:
            CHARTS[path.stem](cols, rows)
        print(f"{path.name:<36} {len(rows):>4} rows")
    (RESULTS / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    conn.close()


if __name__ == "__main__":
    main()
